let errorsPage = `---
title: Errors
description: Every error code Better Files returns, with its HTTP status and what to do about it.
icon: TriangleAlert
---

${banner('packages/core/src/errors.ts')}
Every API throws \`BetterFilesError\`, with a stable \`code\`, an HTTP \`status\`, a message, and optional
\`details\`. Over HTTP the body is \`{ "error": { "code", "message", "details"? } }\`, and the typed client throws the
same codes. Check codes with \`isBetterFilesError(error)\` and \`error.code\`, never the message.

| Code | Status | Meaning |
| --- | --- | --- |
`;
for (const [code, status] of Object.entries(errorStatus))
  errorsPage += `| \`${code}\` | ${status} | ${cell(errorNotes[code] ?? '')} |\n`;
write(join(reference, 'errors.mdx'), errorsPage);

// --- Changelog -------------------------------------------------------------------------------------------------
const changelog = readFileSync(join(root, 'CHANGELOG.md'), 'utf8').replace(/^# Changelog\s*/, '');
write(
  join(reference, 'changelog.md'),
  `---
title: Changelog
description: What changed in each Better Files release, newest first.
icon: History
---

${changelog}`,
);
