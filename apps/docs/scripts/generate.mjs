  INVALID_INPUT:
    'The input failed validation, or names something impossible (a folder moved into itself). `details` lists the issues.',
  UNAUTHENTICATED: 'No valid credential. Sign the person in, or pass the session token or cookie.',
  FORBIDDEN:
    'The identity system or the permission matrix refused the operation, or a plugin gate (an unaccepted NDA) did.',
  NOT_FOUND:
    'The thing does not exist for this caller. Items without the `LIST` capability are reported as not found.',
  CONFLICT:
    'The state does not allow it: a duplicate name, publishing a live room, deleting a room that is not archived.',
  ROOM_CLOSED: 'The room is closed or archived, so content cannot change. Reopen it first.',
  NDA_REQUIRED:
    'The room requires accepting its NDA before this. Show the NDA and call `nda.accept`.',
  MFA_REQUIRED:
    'The room requires multi-factor authentication for this (downloads). Step the person up and retry.',
