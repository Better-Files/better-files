// Generates the data and reference pages the docs site reads from this repository, never from a hand-kept list:
//
//   generated/packages.json  every publishable package: exports, internal dependencies, peers
//   generated/stats.json     counts shown on the home page and social cards
//   content/docs/reference/{operations,actions,capabilities,errors}.mdx and changelog.md
//
// Run after `pnpm build` (the operation matrix, access model and error codes are read from packages/core/dist):
//   node apps/docs/scripts/generate.mjs
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const docs = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const root = resolve(docs, '../..');
const reference = join(docs, 'content/docs/reference');
mkdirSync(join(docs, 'generated'), { recursive: true });
mkdirSync(reference, { recursive: true });

const write = (path, text) => {
  writeFileSync(path, text.endsWith('\n') ? text : `${text}\n`, 'utf8');
  console.log(`wrote ${path.slice(root.length + 1).replaceAll('\\', '/')}`);
};
const banner = (source) =>
  `{/* Generated by apps/docs/scripts/generate.mjs from ${source}. Do not edit; run the script again. */}\n`;
const cell = (text) => String(text).replaceAll('|', '\\|');

// --- Packages --------------------------------------------------------------------------------------------------
const packagesDir = join(root, 'packages');
const manifests = readdirSync(packagesDir)
  .filter((dir) => existsSync(join(packagesDir, dir, 'package.json')))
  .map((dir) => ({
    dir,
    manifest: JSON.parse(readFileSync(join(packagesDir, dir, 'package.json'), 'utf8')),
  }))
  .filter(({ manifest }) => !manifest.private);
const ours = (name) => name === 'better-files' || name.startsWith('@better-files/');
const packages = manifests
  .map(({ dir, manifest }) => ({
    name: manifest.name,
    directory: `packages/${dir}`,
    version: manifest.version,
    description: manifest.description ?? '',
    exports: Object.keys(manifest.exports ?? { '.': {} }).map((subpath) =>
      subpath === '.' ? manifest.name : `${manifest.name}${subpath.slice(1)}`,
    ),
    internalDependencies: Object.keys(manifest.dependencies ?? {}).filter(ours),
    dependencies: Object.keys(manifest.dependencies ?? {}).filter((name) => !ours(name)),
    peerDependencies: Object.keys(manifest.peerDependencies ?? {}),
  }))
  // The umbrella first, then alphabetically.
  .sort((a, b) =>
    a.name === 'better-files' ? -1 : b.name === 'better-files' ? 1 : a.name.localeCompare(b.name),
  );
write(join(docs, 'generated/packages.json'), JSON.stringify(packages, null, 2));

// --- Core metadata from the built core package -----------------------------------------------------------------
const coreDist = join(root, 'packages/core/dist/index.js');
if (!existsSync(coreDist)) throw new Error('packages/core/dist is missing: run `pnpm build` first');
const core = await import(pathToFileURL(coreDist).href);
const {
  operationMatrix,
  coreAccessModel,
  coreActions,
  errorStatus,
  Capability,
  Presets,
  roomRelations,
} = core;

// Plugin actions: every `better-files:{plugin}:{verb}` string a plugin's source declares.
const pluginActions = new Map();
for (const { dir, manifest } of manifests) {
  if (!dir.startsWith('plugin-') && !['mcp', 'viewer', 'storage-cluster'].includes(dir)) continue;
  const src = join(packagesDir, dir, 'src');
  if (!existsSync(src)) continue;
  const found = new Set();
  for (const file of readdirSync(src, { recursive: true })) {
    if (!String(file).endsWith('.ts')) continue;
    const text = readFileSync(join(src, String(file)), 'utf8');
    for (const match of text.matchAll(/'(better-files:[a-z][a-z0-9-]*:[a-z][a-z0-9-]*)'/g))
      if (!coreActions.includes(match[1])) found.add(match[1]);
  }
  if (found.size) pluginActions.set(manifest.name, [...found].sort());
}

// --- Stats -----------------------------------------------------------------------------------------------------
const umbrella = packages.find((pkg) => pkg.name === 'better-files');
const stats = {
  version: umbrella?.version ?? '0.0.0',
  packages: packages.length,
  plugins: packages.filter((pkg) => /\/plugin-/.test(pkg.name)).length,
  subpaths: umbrella ? umbrella.exports.length : 0,
  operations: Object.keys(operationMatrix).length,
  actions:
    coreActions.length + [...pluginActions.values()].reduce((sum, list) => sum + list.length, 0),
  errorCodes: Object.keys(errorStatus).length,
  capabilities: Object.keys(Capability).length,
  relations: roomRelations.length,
};
write(join(docs, 'generated/stats.json'), JSON.stringify(stats, null, 2));

// --- Operations ------------------------------------------------------------------------------------------------
const groups = new Map();
for (const [key, spec] of Object.entries(operationMatrix)) {
  const [group, method] = key.split('.');
  if (!groups.has(group)) groups.set(group, []);
  groups.get(group).push({ key, method, ...spec });
}
const relationsFor = (action) =>
  roomRelations.filter((relation) =>
    coreAccessModel.some(
      (grant) => grant.actions.includes(action) && grant.relations.includes(relation),
    ),
  );
let operationsPage = `---
title: Operations
description: Every core operation, with the action it checks, what it targets, the capabilities it needs, and whether it changes state.
icon: Braces
---

${banner('packages/core/src/operations.ts')}
Each operation is \`dr.api.{group}.{method}\` on the server, the same path on the typed client, and
\`POST {basePath}/{group}/{method}\` over HTTP. Two layers must both allow a call: the
[permission matrix](/docs/guides/concepts/permissions) checks the **capabilities** on the target node, and the
identity system checks the **action** on the room (or the tenant). Plugins add their own operations the same way.

| Column | Meaning |
| --- | --- |
| Target | \`tenant\`: authorized on the tenant. \`room\`: on the room. \`node\`: on a folder or document, with its capabilities checked first. |
| Capabilities | What the caller must hold on the target node (node operations only). |
| Writes | State-changing operations run in one transaction and are refused on closed and archived rooms. |
| Closed rooms | Lifecycle operations that still run once a room is closed. |
| Default relations | Room relations the default access model grants the action to. |
`;
for (const [group, list] of groups) {
  operationsPage += `\n## ${group}\n\n| Operation | Action | Target | Capabilities | Writes | Closed rooms | Default relations |\n| --- | --- | --- | --- | --- | --- | --- |\n`;
  for (const op of list)
    operationsPage += `| \`${op.key}\` | \`${op.action}\` | ${op.target} | ${
      op.capabilities?.length ? op.capabilities.map((c) => `\`${c}\``).join(', ') : ''
    } | ${op.mutates ? 'yes' : ''} | ${op.allowClosed ? 'yes' : ''} | ${
      op.target === 'tenant' ? 'tenant policy' : relationsFor(op.action).join(', ')
    } |\n`;
}
write(join(reference, 'operations.mdx'), operationsPage);

// --- Actions ---------------------------------------------------------------------------------------------------
let actionsPage = `---
title: Actions
description: The identity-system actions Better Files authorizes, which room relations hold each by default, and the actions plugins add.
icon: ShieldCheck
---

${banner('the core access model and plugin sources')}
Actions are what the identity system (Better IAM) decides on, in the \`better-files:\` namespace. The core
registers ${coreActions.length} of them, and \`betterFilesIamPlugin()\` registers each installed plugin's own.
The default access model grants them to room relations as below; change it with your own policies.

## Core actions

| Action | ${roomRelations.join(' | ')} |
| --- | ${roomRelations.map(() => ':-:').join(' | ')} |
`;
for (const action of coreActions)
  actionsPage += `| \`${action}\` | ${roomRelations
    .map((relation) => (relationsFor(action).includes(relation) ? 'yes' : ''))
    .join(' | ')} |\n`;
actionsPage += `\n## Plugin actions\n\nEach plugin's access model decides which relations hold its actions; see the plugin's page.\n\n| Package | Actions |\n| --- | --- |\n`;
for (const [name, list] of [...pluginActions].sort())
  actionsPage += `| \`${name}\` | ${list.map((action) => `\`${action}\``).join(', ')} |\n`;
write(join(reference, 'actions.mdx'), actionsPage);

// --- Capabilities ----------------------------------------------------------------------------------------------
const capabilityNotes = {
  LIST: 'See that the node exists: its name, index number and position in the tree.',
  VIEW: 'Open it in the secure viewer (server-rendered, watermarked pages).',
  PRINT: 'Print from the viewer.',
  COPY_TEXT: 'Select and copy text in the viewer.',
  DOWNLOAD_WATERMARKED: 'Download a copy watermarked for the person downloading it.',
  DOWNLOAD_ORIGINAL: 'Download the original file.',
  UPLOAD: 'Add children to a folder, or new versions to a document.',
  EDIT: 'Rename, move and change metadata; see earlier versions of a document.',
  DELETE: 'Move to the trash and restore.',
  MANAGE: 'Permissions, members and settings for the subtree.',
};
let capabilitiesPage = `---
title: Capabilities
description: The capability bits of the permission matrix, and the presets that bundle them.
icon: Grid
---

${banner('packages/core/src/capabilities.ts')}
A permission entry gives a group or a person a set of capabilities on a folder or document, inherited by
everything under it. Bits 0 to 15 belong to the core; plugins and configuration register their own from bit 16.

## Capabilities

| Capability | Bit | Meaning |
| --- | --- | --- |
`;
for (const [name, value] of Object.entries(Capability))
  capabilitiesPage += `| \`${name}\` | ${Math.log2(value)} | ${cell(capabilityNotes[name] ?? '')} |\n`;
capabilitiesPage += `\n## Presets\n\nPresets are named capability sets for permission entries and groups (\`preset: 'view'\`). Add your own with the \`capabilities.presets\` option.\n\n| Preset | Capabilities |\n| --- | --- |\n`;
for (const [name, list] of Object.entries(Presets))
  capabilitiesPage += `| \`${name}\` | ${list.length ? list.map((c) => (c === '*' ? 'all' : `\`${c}\``)).join(', ') : 'none (hidden)'} |\n`;
write(join(reference, 'capabilities.mdx'), capabilitiesPage);

// --- Errors ----------------------------------------------------------------------------------------------------
